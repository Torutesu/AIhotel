// 巡回する宿泊日の間引き（D-13 — 止められないための量の抑制）。
// 近い日ほど料金がよく動き、推奨にも効くので細かく、遠い日は間引く:
//   0〜30日先は毎日、31〜60日先は2日おき、61〜90日先は4日おき（90日で 53 日 — 毎日取るより4割少ない）

export function selectCrawlDates(stayDates: string[]): string[] {
  return stayDates.filter((_, i) => i <= 30 || (i <= 60 ? (i - 30) % 2 === 0 : (i - 60) % 4 === 0))
}
