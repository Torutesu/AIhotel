import { test, expect, webkit } from '@playwright/test'
test('real DB usage: customer, person, agency groups, assignments and mobile dark isolation',async({page,browser})=>{
 await page.goto('/operations?section=usage')
 await page.getByLabel('メールアドレス',{exact:true}).fill('owner@example.test')
 await page.getByLabel('パスワード',{exact:true}).fill('local-e2e-owner-pass')
 await page.getByRole('button',{name:'ログイン',exact:true}).click()
 await page.getByRole('button',{name:'本番顧客',exact:true}).click()
 await expect(page.getByRole('heading',{name:'顧客別の利用状況',exact:true})).toBeVisible()
 const issued=await page.request.post('/api/demo/operations/agencies',{data:{name:'担当代理店A',email:'production-agent@example.test'}})
 expect(issued.status()).toBe(201)
 const agency=(await issued.json()).data
 await page.getByRole('button',{name:'本番顧客の担当を設定'}).click()
 await page.getByLabel('本番確認用顧客Aの担当代理店',{exact:true}).selectOption(agency.account.id)
 await page.getByRole('button',{name:'担当変更を確定'}).click()
 await expect(page.getByRole('button',{name:'担当変更を確定'})).toHaveCount(0)
 await page.getByRole('dialog').getByRole('button',{name:'閉じる',exact:true}).click()
 await page.getByLabel('本番の集計単位').selectOption('user')
 await expect(page.getByRole('button',{name:/担当者1/})).toBeVisible()
 await page.getByRole('button',{name:/担当者1/}).click()
 await expect(page.getByRole('dialog').getByRole('heading',{name:/担当者1の活用状況/})).toBeVisible()
 await page.keyboard.press('Escape')
 await page.getByLabel('本番の集計単位').selectOption('agency')
 await expect(page.getByRole('button',{name:/担当代理店A/})).toBeVisible()
 const ctx=await browser.newContext(),agent=await ctx.newPage()
 await agent.goto('http://localhost:3100/operations?section=usage')
 await agent.getByLabel('メールアドレス',{exact:true}).fill(agency.account.email)
 await agent.getByLabel('パスワード',{exact:true}).fill(agency.password)
 await agent.getByRole('button',{name:'ログイン',exact:true}).click()
 await agent.getByRole('button',{name:'本番顧客',exact:true}).click()
 await expect(agent.getByRole('button',{name:/本番確認用顧客A/})).toBeVisible()
 await expect(agent.getByText('他社の顧客B')).toHaveCount(0)
 await expect(agent.getByRole('button',{name:'本番顧客の担当を設定'})).toHaveCount(0)
 const report=(await(await agent.request.get('/api/demo/production-usage?tenantIds=usage-browser-b&role=PLATFORM_ADMIN')).json()).data
 expect(report.accounts.every((a:{tenantId:string})=>a.tenantId==='usage-browser-a')).toBe(true)
 expect((await agent.request.put('/api/demo/production-usage',{data:{tenantId:'usage-browser-b',agencyId:agency.account.id}})).status()).toBe(403)
 const safari=await webkit.launch({executablePath:webkit.executablePath()})
 const mobile=await safari.newContext({storageState:await ctx.storageState(),viewport:{width:375,height:812},colorScheme:'dark'})
 await mobile.addInitScript(()=>localStorage.setItem('theme','dark'))
 const phone=await mobile.newPage()
 await phone.goto('http://localhost:3100/operations?section=usage')
 await phone.getByRole('button',{name:'本番顧客',exact:true}).click()
 await phone.getByLabel('本番の集計単位').selectOption('user')
 await expect(phone.getByRole('button',{name:/担当者1/})).toBeVisible()
 expect(await phone.evaluate(()=>document.documentElement.scrollWidth)).toBe(375)
 await phone.screenshot({path:'test-results/production-usage-mobile-dark.png',fullPage:true,animations:'disabled'})
 await phone.getByRole('button',{name:/担当者1/}).click()
 await expect(phone.getByRole('dialog')).toHaveCSS('opacity','1')
 expect(await phone.getByRole('dialog').evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true)
 await phone.screenshot({path:'test-results/production-person-mobile-dark.png',fullPage:true,animations:'disabled'})
 await safari.close()
 await page.request.put('/api/demo/production-usage',{data:{tenantId:'usage-browser-a',agencyId:null}})
 const after=(await(await agent.request.get('/api/demo/production-usage')).json()).data
 expect(after.accounts).toEqual([])
 await ctx.close()
})
